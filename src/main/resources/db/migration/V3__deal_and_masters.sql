-- Deal masters and deal header (UUID PKs; numeric iDempiere IDs replaced)

CREATE TABLE c_currency (
    id UUID PRIMARY KEY,
    iso_code VARCHAR(3) NOT NULL,
    cur_symbol VARCHAR(10),
    description VARCHAR(255) NOT NULL,
    std_precision INTEGER NOT NULL DEFAULT 2,
    costing_precision INTEGER NOT NULL DEFAULT 4,
    is_euro BOOLEAN NOT NULL DEFAULT FALSE,
    is_emu_member BOOLEAN NOT NULL DEFAULT FALSE,
    emu_entry_date TIMESTAMPTZ,
    emu_rate NUMERIC,
    round_off_factor NUMERIC,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    created_by UUID,
    updated_by UUID,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_c_currency_iso UNIQUE (iso_code)
);

CREATE TABLE p_dealtype (
    id UUID PRIMARY KEY,
    value VARCHAR(20) NOT NULL,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(2000),
    contact_mode VARCHAR(20),
    is_instrument_code_applicable BOOLEAN NOT NULL DEFAULT TRUE,
    limit_type VARCHAR(20),
    limit_value NUMERIC,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    created_by UUID,
    updated_by UUID,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_p_dealtype_value UNIQUE (value)
);

CREATE TABLE p_instrumentcode (
    id UUID PRIMARY KEY,
    p_dealtype_id UUID NOT NULL REFERENCES p_dealtype (id),
    value VARCHAR(20) NOT NULL,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(2000),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    created_by UUID,
    updated_by UUID,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_p_instrumentcode_value UNIQUE (value)
);

CREATE INDEX ix_p_instrumentcode_dealtype ON p_instrumentcode (p_dealtype_id);

CREATE TABLE p_dealtypelimit (
    id UUID PRIMARY KEY,
    p_dealtype_id UUID NOT NULL REFERENCES p_dealtype (id),
    c_currency_id UUID REFERENCES c_currency (id),
    date_from TIMESTAMPTZ,
    date_to TIMESTAMPTZ,
    description VARCHAR(255),
    limit_criteria VARCHAR(40),
    limit_type VARCHAR(20),
    limit_value NUMERIC,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    created_by UUID,
    updated_by UUID,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX ix_p_dealtypelimit_dealtype ON p_dealtypelimit (p_dealtype_id);

CREATE TABLE p_nostro (
    id UUID PRIMARY KEY,
    p_counterparty_id UUID,
    c_currency_id UUID NOT NULL REFERENCES c_currency (id),
    value VARCHAR(40) NOT NULL,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(255),
    gl_ac_no VARCHAR(16),
    iban VARCHAR(40),
    swift_code VARCHAR(11),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    created_by UUID,
    updated_by UUID,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_p_nostro_value UNIQUE (value)
);

CREATE TABLE p_deal (
    id UUID PRIMARY KEY,
    document_no VARCHAR(40) NOT NULL,
    p_dealtype_id UUID NOT NULL REFERENCES p_dealtype (id),
    p_instrumentcode_id UUID REFERENCES p_instrumentcode (id),
    ad_user_id UUID REFERENCES ad_user (id),
    approved_by_id UUID REFERENCES ad_user (id),
    rejected_by_id UUID REFERENCES ad_user (id),
    submitted_by_id UUID REFERENCES ad_user (id),
    verified_by_id UUID REFERENCES ad_user (id),
    c_currency_id UUID REFERENCES c_currency (id),
    c_counter_currency_id UUID REFERENCES c_currency (id),
    p_our_nostro_id UUID REFERENCES p_nostro (id),
    p_their_nostro_id UUID REFERENCES p_nostro (id),
    p_counterparty_id UUID,
    ii_counterparty_id UUID,
    iii_counterparty_id UUID,
    alloted_amt NUMERIC,
    alloted_units NUMERIC,
    amount NUMERIC,
    bid_amt NUMERIC,
    contra_amt NUMERIC,
    coupon NUMERIC,
    discounted_price_per_unit NUMERIC,
    discounted_value NUMERIC,
    effective_yield NUMERIC,
    exchange_rate NUMERIC,
    ii_rate NUMERIC,
    iii_rate NUMERIC,
    interest_rate NUMERIC,
    payable_amt NUMERIC,
    rollover_previous_rate NUMERIC,
    rollover_value_amount NUMERIC,
    total_cost NUMERIC,
    total_payable NUMERIC,
    tenure_in_days INTEGER,
    bbg_code VARCHAR(40),
    bond_code VARCHAR(40),
    contact_mode VARCHAR(20),
    cusip_no VARCHAR(20),
    description VARCHAR(2000),
    direction VARCHAR(4),
    direction2 VARCHAR(4),
    doc_action VARCHAR(2) NOT NULL DEFAULT 'CO',
    doc_status VARCHAR(2) NOT NULL DEFAULT 'DR',
    help VARCHAR(2000),
    ii_contact_mode VARCHAR(20),
    ii_contact_person_or_code VARCHAR(120),
    iii_contact_mode VARCHAR(20),
    iii_contact_person_or_code VARCHAR(120),
    interest_payment_frequency VARCHAR(40),
    market_type VARCHAR(40),
    memo_ref_no VARCHAR(40),
    our_custodian VARCHAR(120),
    their_custodian VARCHAR(120),
    reject_reason VARCHAR(2000),
    rollover_deal_ref_no VARCHAR(40),
    rollover_option VARCHAR(4),
    rollover_remarks VARCHAR(2000),
    series VARCHAR(40),
    trader VARCHAR(120),
    bidding_date TIMESTAMPTZ,
    date_approved TIMESTAMPTZ,
    date_rejected TIMESTAMPTZ,
    date_submitted TIMESTAMPTZ,
    date_verified TIMESTAMPTZ,
    deal_date TIMESTAMPTZ,
    deal_time TIMESTAMPTZ,
    last_interest_payment_date TIMESTAMPTZ,
    maturity_date TIMESTAMPTZ,
    memo_approved_date TIMESTAMPTZ,
    next_interest_payment_date TIMESTAMPTZ,
    original_issue_date TIMESTAMPTZ,
    rollover_previous_value_date TIMESTAMPTZ,
    value_date TIMESTAMPTZ,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_rollover BOOLEAN NOT NULL DEFAULT FALSE,
    processed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    created_by UUID,
    updated_by UUID,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_p_deal_document_no UNIQUE (document_no)
);

CREATE INDEX ix_p_deal_dealtype ON p_deal (p_dealtype_id);
CREATE INDEX ix_p_deal_user ON p_deal (ad_user_id);
CREATE INDEX ix_p_deal_deal_date ON p_deal (deal_date);
